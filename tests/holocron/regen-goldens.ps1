<#
    regen-goldens.ps1 - regenerates the Holocron golden files under
    testdata\golden\ from the PowerShell product (the specification of "today's
    behaviour"), or with -Verify regenerates them into a temp folder and fails
    on any difference from the committed files.

        powershell.exe -NoProfile -ExecutionPolicy Bypass -File tests\holocron\regen-goldens.ps1
        powershell.exe -NoProfile -ExecutionPolicy Bypass -File tests\holocron\regen-goldens.ps1 -Verify

    Every group is generated by calling the product's own functions with FAKE
    inputs (Camera One ..., 192.0.2.x, fakeuser / fakepass). Nothing real is
    read; no port, process, task or real folder is touched.
#>
param([switch]$Verify)

$ErrorActionPreference = 'Stop'
. (Join-Path -Path $PSScriptRoot -ChildPath 'holocron-lib.ps1')
. (Join-Path -Path $PSScriptRoot -ChildPath 'status-docs.ps1')
foreach ($group in @('golden-ffmpeg.ps1', 'golden-relay.ps1', 'golden-names.ps1')) { . (Join-Path -Path $PSScriptRoot -ChildPath $group) }

Assert-HolocronEnvironment

$goldenRoot = Join-Path -Path (Get-HolocronRepo) -ChildPath 'testdata\golden'
$target = $goldenRoot
$temp = $null
if ($Verify) {
    $temp = New-HolocronSandbox
    $target = Join-Path -Path $temp -ChildPath 'golden'
}

try {
    # ---- group: status fixtures (positive and negative)
    $statusDir = Join-Path -Path $target -ChildPath 'status'
    foreach ($dir in @($statusDir, (Join-Path $statusDir 'negative'))) {
        if (Test-Path -LiteralPath $dir) { Get-ChildItem -LiteralPath $dir -Filter '*.json' | Remove-Item -Force }
        [void](New-Item -ItemType Directory -Path $dir -Force)
    }
    $observed = New-HolocronStatusDocuments -OutDir $statusDir -Deterministic
    if ($observed.F1BeforeHadLastWindowClose -ne $true -or $observed.F1AfterHasLastWindowClose -ne $false) { throw 'F1 is no longer observed: update KNOWN-DIFFERENCES.md and the schema tests' }
    if ($observed.WindowClosedRejectedByWriter -ne $true) { throw 'the writer now accepts window-closed: update KNOWN-DIFFERENCES.md' }
    New-HolocronNegativeStatusDocuments -SourceDir $statusDir -OutDir (Join-Path $statusDir 'negative')

    # ---- group: ffmpeg argument vectors
    New-HolocronFfmpegGoldens -OutDir $target

    # ---- group: relay and live MediaMTX configs
    New-HolocronRelayGoldens -OutDir $target

    # ---- group: safe names and segment names
    New-HolocronNameGoldens -OutDir $target

    # ---- compare, in -Verify mode
    if ($Verify) {
        $differences = 0
        $checked = 0
        $files = @(Get-ChildItem -LiteralPath $target -Recurse -File)
        foreach ($file in $files) {
            $relative = $file.FullName.Substring($target.Length).TrimStart('\')
            $committed = Join-Path -Path $goldenRoot -ChildPath $relative
            $checked++
            if (-not (Test-Path -LiteralPath $committed)) { Write-Host "DIFF  $relative : not committed"; $differences++; continue }
            if ((Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash -ne (Get-FileHash -LiteralPath $committed -Algorithm SHA256).Hash) {
                Write-Host "DIFF  $relative : bytes differ"; $differences++
            }
        }
        # Files that are committed but no longer produced.
        $known = @{}
        foreach ($file in $files) { $known[$file.FullName.Substring($target.Length).TrimStart('\')] = $true }
        foreach ($file in @(Get-ChildItem -LiteralPath $goldenRoot -Recurse -File)) {
            $relative = $file.FullName.Substring($goldenRoot.Length).TrimStart('\')
            if ($relative -like 'README.md' -or $relative -like '.gitkeep' -or $relative -like 'status\generated\*') { continue }
            if (-not $known.ContainsKey($relative)) { Write-Host "DIFF  $relative : committed but not produced"; $differences++ }
        }
        Write-Host ("verify: {0} generated files compared, {1} differences" -f $checked, $differences)
        if ($differences -gt 0) { exit 1 }
    }
    else {
        Write-Host ("regenerated the goldens under {0}" -f $goldenRoot)
    }
}
finally { if ($temp) { Remove-HolocronSandbox -Path $temp } }
