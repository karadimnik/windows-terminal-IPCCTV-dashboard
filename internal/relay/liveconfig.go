package relay

import (
	"fmt"
	"strings"

	"holocron/internal/config"
)

// LiveInputs is everything the live instance's config depends on. Config supplies RelayBase (the
// main paths read the recording relay), LiveWhepAddress, LiveUdpAddress, LiveAdvertiseHosts,
// LiveSubStream and LiveCloseAfterSeconds, already validated by config.Load: the address and host
// rules live there and are not repeated here. Login is the camlive login.
type LiveInputs struct {
	Config  config.Config
	Cameras []config.Camera
	Login   Login
}

// LiveConfig is Get-CamLiveConfigText: the whole live config rendered in code, CRLF, byte for byte
// what PowerShell renders. No anonymous user, no origins, every server but WebRTC off; the secret
// appears only as its SHA-256; camera credentials arrive in the environment (LiveSourceEnv).
func LiveConfig(in LiveInputs) ([]byte, error) {
	cfg := in.Config
	paths, err := LivePaths(in.Cameras, cfg)
	if err != nil {
		return nil, err
	}
	if err := checkLogin(in.Login); err != nil {
		return nil, err
	}
	hosts := append([]string{"127.0.0.1"}, cfg.LiveAdvertiseHosts...)
	for _, v := range append([]string{cfg.LiveWhepAddress, cfg.LiveUdpAddress}, hosts...) {
		if err := checkScalar("live address", v); err != nil {
			return nil, err
		}
	}
	relayBase := strings.TrimRight(cfg.RelayBase, "/")
	if err := checkScalar("RelayBase", strings.TrimPrefix(strings.TrimPrefix(relayBase, "rtsp://"), "rtsps://")); err != nil {
		return nil, err
	}
	if err := checkScalar("live sub stream", cfg.LiveSubStream); err != nil {
		return nil, err
	}

	lines := make([]string, 0, 3*len(paths))
	for _, p := range paths {
		lines = append(lines, "  "+p.Name+":")
		if p.Kind == LiveSub {
			lines = append(lines,
				fmt.Sprintf("    # %s %s - source supplied at launch by %s", oneLine(p.Camera.Name), cfg.LiveSubStream, SourceEnvName(p.Name)),
				"    source: publisher")
		} else {
			lines = append(lines,
				fmt.Sprintf("    # %s through the recording relay - no credential, no extra camera session", oneLine(p.Camera.Name)),
				"    source: "+relayBase+"/"+p.RelayPath)
		}
	}
	quoted := make([]string, len(hosts))
	for i, h := range hosts {
		quoted[i] = `"` + h + `"`
	}

	text := `# Generated by cam.recorder.ps1 for live view. Do not edit: the supervisor rewrites it at every start.
logLevel: info
logDestinations: [stdout]
readTimeout: 10s
writeTimeout: 10s
writeQueueSize: 512

authMethod: internal
authInternalUsers:
  - user: ` + in.Login.User + `
    pass: ` + in.Login.PassHash() + `
    ips: ["127.0.0.1", "::1"]
    permissions:
      - action: read

api: no
metrics: no
pprof: no
playback: no
rtsp: no
rtmp: no
hls: no
srt: no
moq: no

webrtc: yes
webrtcAddress: ` + cfg.LiveWhepAddress + `
webrtcEncryption: no
webrtcAllowOrigins: []
webrtcTrustedProxies: []
webrtcLocalUDPAddress: ` + cfg.LiveUdpAddress + `
webrtcLocalTCPAddress: ""
webrtcIPsFromInterfaces: no
webrtcIPsFromInterfacesList: []
webrtcAdditionalHosts: [` + strings.Join(quoted, ", ") + `]
webrtcICEServers2: []

pathDefaults:
  rtspTransport: tcp
  sourceOnDemand: yes
  sourceOnDemandStartTimeout: 10s
  sourceOnDemandCloseAfter: ` + fmt.Sprint(cfg.LiveCloseAfterSeconds) + `s

paths:
` + strings.Join(lines, "\n")
	return []byte(crlf(text)), nil
}
